type Dependency struct {
	Git        string   `toml:"git,omitempty"`
	Path       string   `toml:"path,omitempty"`
	Branch     string   `toml:"branch,omitempty"`
	Tag        string   `toml:"tag,omitempty"`
	Rev        string   `toml:"rev,omitempty"`
	Root       string   `toml:"root,omitempty"`
	Skills     []string `toml:"skills,omitempty"`
	Link       bool     `toml:"link,omitempty"`
	Transitive bool     `toml:"transitive,omitempty"`
}

func Local(path string) string {
	ext := filepath.Ext(path)
	return strings.TrimSuffix(path, ext) + ".local" + ext
}

type Scope struct {
	Manifest string
	Lock     string
	State    string
	Store    string
	Tools    string
	Log      io.Writer
}

type Report struct {
	Packages []string
	Deployed int
	Removed  int
}

var ErrNoPhora = errors.New("henia needs phora to fetch dependencies, and no release fits this platform; install it from https://github.com/srnnkls/phora or set HENIA_PHORA")

var name = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]*$`)

func (d Dependency) validate(key string) error {
	if !name.MatchString(key) {
		return fmt.Errorf("dependency %q: names are lowercase letters, digits, dots, underscores and hyphens", key)
	}
	if reference.Reserved(key) {
		return fmt.Errorf("dependency %q: %s is an address kind, not a package name", key, key)
	}
	if (d.Git == "") == (d.Path == "") {
		return fmt.Errorf("dependency %s needs exactly one of git or path", key)
	}
	refs := 0
	for _, ref := range []string{d.Branch, d.Tag, d.Rev} {
		if ref != "" {
			refs++
		}
	}
	if refs > 1 {
		return fmt.Errorf("dependency %s takes at most one of branch, tag and rev", key)
	}
	if d.Path != "" && refs > 0 {
		return fmt.Errorf("dependency %s: a path dependency has no branch, tag or rev", key)
	}
	if d.Link && d.Path == "" {
		return fmt.Errorf("dependency %s: link deploys a path dependency live; it needs path", key)
	}
	if d.Transitive && (d.Root != "" || len(d.Skills) > 0) {
		return fmt.Errorf("dependency %s: a transitive package ships what its phora.toml publishes; it takes no root or skills", key)
	}
	return nil
}

func Read(manifest string) (map[string]Dependency, error) {
	data, err := os.ReadFile(manifest)
	if errors.Is(err, os.ErrNotExist) {
		return map[string]Dependency{}, nil
	}
	if err != nil {
		return nil, err
	}
	var file struct {
		Dependencies map[string]Dependency `toml:"dependencies"`
	}
	if err := toml.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("%s: %w", manifest, err)
	}
	if file.Dependencies == nil {
		file.Dependencies = map[string]Dependency{}
	}
	for key, d := range file.Dependencies {
		if err := d.validate(key); err != nil {
			return nil, fmt.Errorf("%s: %w", manifest, err)
		}
		if rest, ok := strings.CutPrefix(d.Path, "~/"); ok {
			if home, err := os.UserHomeDir(); err == nil {
				d.Path = filepath.Join(home, rest)
			}
		}
		if d.Path != "" && !filepath.IsAbs(d.Path) {
			d.Path = filepath.Join(filepath.Dir(manifest), d.Path)
		}
		file.Dependencies[key] = d
	}
	return file.Dependencies, nil
}

func phoraManifest(dependencies map[string]Dependency, scope Scope) ([]byte, error) {
	relative, err := filepath.Rel(scope.State, scope.Store)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Generated by henia from its [dependencies]; edits are overwritten.\n")
	for _, key := range slices.Sorted(maps.Keys(dependencies)) {
		d := dependencies[key]
		fmt.Fprintf(&b, "\n[sources.%s]\n", key)
		if d.Git != "" {
			fmt.Fprintf(&b, "git = %s\n", strconv.Quote(d.Git))
		} else {
			fmt.Fprintf(&b, "path = %s\n", strconv.Quote(d.Path))
		}
		for _, ref := range []struct{ key, value string }{{"branch", d.Branch}, {"tag", d.Tag}, {"rev", d.Rev}, {"root", d.Root}} {
			if ref.value != "" {
				fmt.Fprintf(&b, "%s = %s\n", ref.key, strconv.Quote(ref.value))
			}
		}
		if d.Link {
			b.WriteString("deploy = \"link\"\n")
		}
		if d.Transitive {
			b.WriteString("transitive = true\n")
		}
		carried, err := d.resources(key, scope)
		if err != nil {
			return nil, err
		}
		if len(d.Skills) > 0 {
			quoted := []string{strconv.Quote("henia.toml"), strconv.Quote(".henia/")}
			for _, skill := range d.Skills {
				quoted = append(quoted, strconv.Quote("skills/"+skill+"/"))
			}
			for _, c := range carried {
				quoted = append(quoted, strconv.Quote(c.Source))
			}
			fmt.Fprintf(&b, "include = [%s]\n", strings.Join(quoted, ", "))
		}
		fmt.Fprintf(&b, "\n[targets.%s]\npath = %s\n", key, strconv.Quote(filepath.ToSlash(filepath.Join(relative, key))))
		if len(carried) == 0 {
			fmt.Fprintf(&b, "sources = [%s]\n", strconv.Quote(key))
			continue
		}
		take := []string{strconv.Quote("**")}
		for _, c := range carried {
			take = append(take, fmt.Sprintf("{ %s = %s }", strconv.Quote(c.Source), strconv.Quote(strings.TrimSuffix(c.Path, "/"))))
		}
		collapse := ""
		if d.Link {
			collapse = ", collapse = false"
		}
		fmt.Fprintf(&b, "\n[targets.%s.sources]\n%s = { take = [%s]%s }\n", key, key, strings.Join(take, ", "), collapse)
	}
	return []byte(b.String()), nil
}

// resources lists the package resources the skills of d declare, with Path
// rooted at the package. A path dependency declares them in its working tree,
// any other in its deployed copy; a package the store does not hold yet
// declares none.
func (d Dependency) resources(key string, scope Scope) ([]artifact.PackageResource, error) {
	root := filepath.Join(scope.Store, key)
	if d.Path != "" {
		root = filepath.Join(d.Path, filepath.FromSlash(d.Root))
	}
	carried, err := packageResources(root, d.Skills)
	if err != nil {
		return nil, fmt.Errorf("dependency %s: %w", key, err)
	}
	return carried, nil
}

// uncollapse removes the directory links a linked deployment holds where
// package resources land, which phora would write through into the package.
func uncollapse(root string, carried []artifact.PackageResource) error {
	for _, c := range carried {
		segments := strings.Split(strings.TrimSuffix(c.Path, "/"), "/")
		if !c.Dir() {
			segments = segments[:len(segments)-1]
		}
		at := root
		for _, segment := range segments {
			at = filepath.Join(at, segment)
			info, err := os.Lstat(at)
			if errors.Is(err, os.ErrNotExist) {
				break
			}
			if err != nil {
				return err
			}
			if info.Mode()&os.ModeSymlink != 0 {
				if err := os.Remove(at); err != nil {
					return err
				}
				break
			}
		}
	}
	return nil
}

func packageResources(root string, skills []string) ([]artifact.PackageResource, error) {
	if len(skills) == 0 {
		entries, err := os.ReadDir(filepath.Join(root, "skills"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		for _, entry := range entries {
			skills = append(skills, entry.Name())
		}
	}
	var carried []artifact.PackageResource
	for _, skill := range skills {
		data, err := os.ReadFile(filepath.Join(root, "skills", skill, "SKILL.md"))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		art, err := artifact.Parse(data)
		if err != nil {
			continue
		}
		resources, err := art.PackageResources()
		if err != nil {
			return nil, fmt.Errorf("skill %s: %w", skill, err)
		}
		for _, r := range resources {
			carried = append(carried, artifact.PackageResource{Path: "skills/" + skill + "/" + r.Path, Source: r.Source})
		}
	}
	return carried, nil
}

func Sync(ctx context.Context, scope Scope, update bool) (Report, error) {
	phora, err := Phora(ctx, scope.Tools, scope.Log)
	if err != nil {
		return Report{}, err
	}
	declared, err := Read(scope.Manifest)
	if err != nil {
		return Report{}, err
	}
	overrides, err := Read(Local(scope.Manifest))
	if err != nil {
		return Report{}, err
	}
	var report Report
	if err := os.MkdirAll(scope.State, 0o755); err != nil {
		return report, err
	}
	state := func(name string) string { return filepath.Join(scope.State, name) }
	if err := copyFile(scope.Lock, state("phora.lock")); err != nil {
		return report, err
	}
	if err := copyFile(Local(scope.Lock), state("phora.local.lock")); err != nil {
		return report, err
	}
	command := "sync"
	if update {
		command = "update"
	}
	// The first pass already names the transitive packages the store holds:
	// phora keeps only the lock entries of the sources a manifest names, and
	// a dropped entry would resolve to its branch head on the next pass. The
	// store may predate the manifest, so a conflict in it only drops the seed.
	top := declared
	if seeded, err := closure(top, overrides, scope); err == nil {
		declared = seeded
	}
	// A pass repeats while it brings in packages or skill resources that
	// change what a package ships.
	for {
		written, err := writeManifests(declared, overrides, scope)
		if err != nil {
			return report, err
		}
		if err := uncollapseLinked(declared, overrides, scope); err != nil {
			return report, err
		}
		summary, err := run(ctx, phora, command, scope.State)
		if err != nil {
			return report, err
		}
		report.Deployed += summary.Deployed
		report.Removed += summary.Removed
		next, err := closure(top, overrides, scope)
		if err != nil {
			return report, err
		}
		if maps.EqualFunc(next, declared, equal) {
			again, err := manifests(declared, overrides, scope)
			if err != nil {
				return report, err
			}
			if slices.EqualFunc(again, written, bytes.Equal) {
				break
			}
		}
		declared = next
	}
	effective := maps.Clone(declared)
	maps.Copy(effective, overrides)
	if len(effective) == 0 {
		if err := os.Remove(scope.Lock); err != nil && !errors.Is(err, os.ErrNotExist) {
			return report, err
		}
	} else if len(overrides) == 0 {
		if err := copyFile(state("phora.lock"), scope.Lock); err != nil {
			return report, err
		}
	} else if err := mergeLock(state("phora.lock"), scope.Lock, overrides); err != nil {
		return report, err
	}
	if err := copyFile(state("phora.local.lock"), Local(scope.Lock)); err != nil {
		return report, err
	}
	report.Packages = slices.Sorted(maps.Keys(effective))
	return report, nil
}

// closure is top with the packages its deployed packages declare, transitively;
// a package the store does not hold yet contributes nothing.
func closure(top, overrides map[string]Dependency, scope Scope) (map[string]Dependency, error) {
	declared := maps.Clone(top)
	origin := map[string]string{}
	for key := range top {
		origin[key] = scope.Manifest
	}
	for added := true; added; {
		added = false
		effective := maps.Clone(declared)
		maps.Copy(effective, overrides)
		for _, key := range slices.Sorted(maps.Keys(effective)) {
			for _, candidate := range []string{filepath.Join(scope.Store, key, "henia.toml"), filepath.Join(scope.Store, key, ".henia", "henia.toml")} {
				transitive, err := Read(candidate)
				if err != nil {
					return nil, err
				}
				for child, d := range transitive {
					if existing, ok := declared[child]; ok {
						if _, overridden := overrides[child]; !overridden && !equal(existing, d) {
							return nil, fmt.Errorf("dependency %s is declared differently by %s and %s", child, origin[child], candidate)
						}
						continue
					}
					declared[child], origin[child], added = d, candidate, true
				}
			}
		}
	}
	return declared, nil
}

func manifests(declared, overrides map[string]Dependency, scope Scope) ([][]byte, error) {
	shared := maps.Clone(declared)
	for key := range overrides {
		delete(shared, key)
	}
	main, err := phoraManifest(shared, scope)
	if err != nil {
		return nil, err
	}
	if len(overrides) == 0 {
		return [][]byte{main, nil}, nil
	}
	local, err := phoraManifest(overrides, scope)
	if err != nil {
		return nil, err
	}
	return [][]byte{main, local}, nil
}

func uncollapseLinked(declared, overrides map[string]Dependency, scope Scope) error {
	effective := maps.Clone(declared)
	maps.Copy(effective, overrides)
	for key, d := range effective {
		if !d.Link {
			continue
		}
		carried, err := d.resources(key, scope)
		if err != nil {
			return err
		}
		if err := uncollapse(filepath.Join(scope.Store, key), carried); err != nil {
			return err
		}
	}
	return nil
}

func writeManifests(declared, overrides map[string]Dependency, scope Scope) ([][]byte, error) {
	generated, err := manifests(declared, overrides, scope)
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(scope.State, "phora.toml"), generated[0], 0o644); err != nil {
		return nil, err
	}
	local := filepath.Join(scope.State, "phora.local.toml")
	if generated[1] == nil {
		if err := os.Remove(local); err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
	} else if err := os.WriteFile(local, generated[1], 0o644); err != nil {
		return nil, err
	}
	return generated, nil
}

type lockFile struct {
	Version int              `toml:"version"`
	Sources []map[string]any `toml:"sources"`
}

func mergeLock(fresh, tracked string, overrides map[string]Dependency) error {
	var next, previous lockFile
	for _, f := range []struct {
		path string
		into *lockFile
	}{{fresh, &next}, {tracked, &previous}} {
		data, err := os.ReadFile(f.path)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if err := toml.Unmarshal(data, f.into); err != nil {
			return fmt.Errorf("%s: %w", f.path, err)
		}
	}
	for _, entry := range previous.Sources {
		if name, _ := entry["name"].(string); hasKey(overrides, name) {
			next.Sources = append(next.Sources, entry)
		}
	}
	slices.SortFunc(next.Sources, func(a, b map[string]any) int {
		x, _ := a["name"].(string)
		y, _ := b["name"].(string)
		return strings.Compare(x, y)
	})
	if next.Version == 0 {
		next.Version = previous.Version
	}
	if reflect.DeepEqual(next, previous) {
		return nil
	}
	data, err := toml.Marshal(next)
	if err != nil {
		return err
	}
	return os.WriteFile(tracked, data, 0o644)
}

func hasKey(m map[string]Dependency, key string) bool {
	_, ok := m[key]
	return ok
}

func copyFile(from, to string) error {
	data, err := os.ReadFile(from)
	if errors.Is(err, os.ErrNotExist) {
		if err := os.Remove(to); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		return nil
	}
	if err != nil {
		return err
	}
	return os.WriteFile(to, data, 0o644)
}

func equal(a, b Dependency) bool {
	return a.Git == b.Git && a.Path == b.Path && a.Branch == b.Branch && a.Tag == b.Tag && a.Rev == b.Rev && a.Root == b.Root && slices.Equal(a.Skills, b.Skills) && a.Transitive == b.Transitive
}

type summary struct {
	Deployed int `json:"deployed"`
	Removed  int `json:"removed"`
	Failures int `json:"failures"`
}

func run(ctx context.Context, phora, command, dir string) (summary, error) {
	args := []string{command, "-C", dir, "--prune"}
	if command == "sync" {
		args = append(args, "--json", "--no-progress")
	}
	cmd := exec.CommandContext(ctx, phora, args...)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err := cmd.Run()
	var result summary
	var problems []string
	scanner := bufio.NewScanner(&stdout)
	for scanner.Scan() {
		var event map[string]any
		if json.Unmarshal(scanner.Bytes(), &event) != nil {
			continue
		}
		switch event["type"] {
		case "summary":
			_ = json.Unmarshal(scanner.Bytes(), &result)
		case "error", "failure", "failed":
			if message, ok := event["message"].(string); ok {
				problems = append(problems, message)
			}
		}
	}
	if err != nil || result.Failures > 0 {
		detail := strings.TrimSpace(strings.Join(append(problems, stderr.String()), "\n"))
		if detail == "" {
			detail = strings.TrimSpace(stdout.String())
		}
		return result, fmt.Errorf("phora %s failed: %s", command, detail)
	}
	return result, nil
}
